"""Construct UxPlay arguments; separate from GUI and process lifecycle."""

from __future__ import annotations

from .settings import Settings


def build_uxplay_args(
    settings: Settings, *, pairing_mode: bool, allowed_ids: list[str], pairing_pin: str | None = None
) -> list[str]:
    args = [
        "-n", settings.receiver_name.strip(),
        "-key", settings.key_file,
        "-pin", "-reg", settings.registration_file,
    ]
    if pairing_mode:
        if pairing_pin is None or len(pairing_pin) != 4 or not pairing_pin.isascii() or not pairing_pin.isdigit():
            raise ValueError("새 iPad 등록에 사용할 4자리 PIN이 필요합니다.")
        # The PIN is ephemeral, generated by the controller for each enrollment
        # server start. It is not written to local configuration or GUI logs.
        pin_pos = args.index("-pin")
        args.insert(pin_pos + 1, pairing_pin)
    if not pairing_mode:
        if not allowed_ids:
            raise ValueError("등록된 기기가 없습니다. 먼저 '새 iPad 등록'을 선택하세요.")
        args.append("-restrict")
        for device_id in allowed_ids:
            args.extend(["-allow", device_id])
    # Pairing mode is deliberately temporary and requires the user to click
    # '새 iPad 등록'. During that mode every client must pass -pin pairing.
    args.extend(["-vd", "avdec_h264", "-vs", "d3d11videosink"])
    # Keep default video/audio timestamp synchronization: the user verified it.
    if not settings.audio_enabled:
        args.extend(["-as", "0"])
    return args
